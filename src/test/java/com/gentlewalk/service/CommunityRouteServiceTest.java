package com.gentlewalk.service;

import com.gentlewalk.api.dto.CreateCommunityRouteRequest;
import com.gentlewalk.domain.CommunityRoute;
import com.gentlewalk.domain.CommunityStop;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;

import java.util.List;
import java.util.Optional;

import static org.junit.jupiter.api.Assertions.*;

class CommunityRouteServiceTest {

    private CommunityRouteService service;

    @BeforeEach
    void setUp() {
        service = new CommunityRouteService();
    }

    @Test
    void testInitialSeedRoutesPresent() {
        List<CommunityRoute> routes = service.getRoutes(null, null, null);
        assertNotNull(routes);
        assertTrue(routes.size() >= 5, "Should have at least 5 seeded community routes");
        assertTrue(routes.stream().anyMatch(r -> r.title().contains("Lodhi")));
        assertTrue(routes.stream().anyMatch(r -> r.title().contains("Cubbon")));
        assertTrue(routes.stream().anyMatch(r -> r.title().contains("Sehore")));
    }

    @Test
    void testProximitySorting() {
        // Search near Sehore (23.0756, 76.8596)
        List<CommunityRoute> routes = service.getRoutes(23.0756, 76.8596, 50.0);
        assertFalse(routes.isEmpty());
        // Sehore route should be first
        assertEquals("cr-sehore-1", routes.get(0).id());
    }

    @Test
    void testSubmitRouteWithAutoGeneratedStops() {
        List<List<Double>> coords = List.of(
                List.of(77.200, 28.600),
                List.of(77.201, 28.601),
                List.of(77.202, 28.602),
                List.of(77.203, 28.603),
                List.of(77.204, 28.602),
                List.of(77.205, 28.601),
                List.of(77.200, 28.600)
        );

        CreateCommunityRouteRequest req = new CreateCommunityRouteRequest(
                "Dadi's Morning Chai Trail",
                "Mrs. Gupta (Age 71)",
                "Lovely shaded avenue with flower stalls and fresh chai.",
                List.of("🌸 Floral", "🪑 Benches", "☕ Chai Stop"),
                28.600, 77.200,
                1100.0, 18, 4, 15.0, "GREEN",
                coords,
                List.of() // empty stops to trigger auto-generation
        );

        CommunityRoute created = service.submitRoute(req);
        assertNotNull(created);
        assertNotNull(created.id());
        assertEquals("Dadi's Morning Chai Trail", created.title());
        assertEquals("Mrs. Gupta (Age 71)", created.author());
        assertFalse(created.stops().isEmpty(), "Auto-generated rest stops should be populated");
        assertEquals(1, created.walkersCount());
        assertEquals(1, created.cheersCount());

        // Verify route is retrievable
        Optional<CommunityRoute> fetched = service.getRoute(created.id());
        assertTrue(fetched.isPresent());
        assertEquals(created.id(), fetched.get().id());
    }

    @Test
    void testCheerAndLogWalk() {
        Optional<CommunityRoute> cheered = service.cheerRoute("cr-lodhi-1");
        assertTrue(cheered.isPresent());
        assertTrue(cheered.get().cheersCount() > 42);

        Optional<CommunityRoute> walked = service.logWalk("cr-lodhi-1");
        assertTrue(walked.isPresent());
        assertTrue(walked.get().walkersCount() > 64);
    }
}
